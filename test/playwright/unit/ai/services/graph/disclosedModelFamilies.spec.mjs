import {test, expect} from '@playwright/test';

import {disclosedFamiliesOf} from '../../../../../../ai/services/graph/disclosedModelFamilies.mjs';

/**
 * The disclosure lines below follow outside pull requests opened across `neomjs` between 2026-11-01 and
 * 2026-11-14 word for word, with the contributors' names replaced, so a failure points at wording a
 * contributor actually used rather than at a constructed case.
 */
test.describe('ai/services/graph/disclosedModelFamilies — what an outside pull request names', () => {
    test('a Claude disclosure, in each form the census found', () => {
        expect(disclosedFamiliesOf({body: 'Some prose.\n\n🤖 Generated with [Claude Code](https://claude.com/claude-code)'})).toEqual(['claude']);
        expect(disclosedFamiliesOf({body: 'Authored by Jo Doe (@jodoe), assisted by Claude Opus 5.5 (Claude Code).'})).toEqual(['claude']);
        expect(disclosedFamiliesOf({body: '- [x] It\'s submitted to the `dev` branch\n\nMade with Claude Code (Claude Opus 5.5).'})).toEqual(['claude'])
    });

    test('a GPT disclosure, under a heading, after a label, or as a sentence', () => {
        expect(disclosedFamiliesOf({body: '## AI Disclosure\n\nPrepared with OpenAI Codex (GPT-6.1).'})).toEqual(['gpt']);
        expect(disclosedFamiliesOf({body: '### AI assistance\nAI assistance: ChatGPT (GPT-6) assisted with code analysis and implementation.'})).toEqual(['gpt']);
        expect(disclosedFamiliesOf({body: '### AI Assistance\n\nUsed GPT-6 for step-by-step implementation guidance. I reviewed the changes and ran the tests locally.'})).toEqual(['gpt'])
    });

    test('a family no seat belongs to still counts as named', () => {
        expect(disclosedFamiliesOf({body: 'Authored by Sam with an AI coding agent (OpenCode, DeepSeek V4.1 Flash) under human supervision.'})).toEqual(['deepseek']);
        expect(disclosedFamiliesOf({body: '## Model disclosure\n\nGenerated by an AI agent: provider Nous Research (Ollama Cloud), model `deepseek-v4.1-flash`, driven by the Hermes agent framework.'})).toEqual(['deepseek'])
    });

    test('a harness alone names no family', () => {
        // Cursor and Copilot each run several vendors' models
        expect(disclosedFamiliesOf({body: '---\n**AI disclosure:** This change was written with AI assistance (Cursor). I followed the verb-list precedent.'})).toEqual([]);
        expect(disclosedFamiliesOf({commitMessages: ['fix: x\n\nCo-authored-by: Copilot <223556219+Copilot@users.noreply.github.com>']})).toEqual([])
    });

    test('a commit trailer names the family when the body does not', () => {
        // The body names nothing; the first commit carries the trailer, the head does not
        const commitMessages = [
            'feat(grid): expand and collapse a tree grid row with ArrowRight and ArrowLeft\n\nCo-Authored-By: Claude Fable 5.1 <noreply@anthropic.com>',
            'test(grid): cover the collapsed row'
        ];

        expect(disclosedFamiliesOf({body: 'Resolves #20760\n\nThe tree grid now expands a row on ArrowRight.', commitMessages})).toEqual(['claude'])
    });

    test('a trailer on any commit counts, not only on the first or the head', () => {
        const commitMessages = ['chore: set up', 'feat: the change\n\nCo-Authored-By: Claude Fable 5.1 <noreply@anthropic.com>', 'chore: tidy'];

        expect(disclosedFamiliesOf({body: 'Resolves #1', commitMessages})).toEqual(['claude'])
    });

    test('a commit\'s subject and body name its topic, never its author: only its trailer does', () => {
        const body = 'AI disclosure: OpenAI Codex';

        expect(disclosedFamiliesOf({body, commitMessages: ['Implemented support for Claude and Gemini endpoints.']})).toEqual(['gpt']);
        expect(disclosedFamiliesOf({body, commitMessages: ['feat: generated the Gemini client\n\nMade with the Claude API docs open.']})).toEqual(['gpt']);
        expect(disclosedFamiliesOf({body, commitMessages: ['feat: the Gemini client\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>']})).toEqual(['claude', 'gpt'])
    });

    test('a provider\'s model id and a versioned model name name their family, and a path still does not', () => {
        expect(disclosedFamiliesOf({body: 'AI disclosure: anthropic/claude-sonnet-4-5'})).toEqual(['claude']);
        expect(disclosedFamiliesOf({body: 'AI disclosure: Qwen3-Coder'})).toEqual(['qwen']);
        expect(disclosedFamiliesOf({body: 'Generated with OpenCode (`meta-llama/Llama-3.1-70B-Instruct`).'})).toEqual(['llama']);
        expect(disclosedFamiliesOf({body: 'AI disclosure: Claude Code; it rewrites `.gemini/concepts/model.md` and `docs/gemini/setup.md`.'})).toEqual(['claude'])
    });

    test('a path or a topic sentence is not a disclosure', () => {
        expect(disclosedFamiliesOf({body: '## Changes\n\n1. **Deleted `.gemini/concepts/worktree-bootstrap.md`** — it was the only tracked file under `.gemini/`.'})).toEqual([]);
        expect(disclosedFamiliesOf({body: 'Claude Code doesn\'t read `autoMode` from project settings, so this block in `.claude/settings.template.json` was never applied.'})).toEqual([]);
        // A disclosure line that also mentions a path keeps only its author
        expect(disclosedFamiliesOf({body: 'Authored by Jo (Claude Opus 5.5, Claude Code); it moves `.gemini/settings.json`.'})).toEqual(['claude'])
    });

    test('the contributor template asks on an `AI disclosure` line: unfilled it names nothing, filled it names its family', () => {
        const template = [
            'Please make sure to read the Contributing Guidelines:',
            '',
            '**Does this PR resolve an issue?** (Required)',
            '',
            'Resolves #',
            '',
            '**What kind of change does this PR introduce?** (check at least one)',
            '',
            '- [ ] Bugfix',
            '- [ ] Feature',
            '- [ ] Build-related changes',
            '',
            '**The PR fulfills this requirement:**',
            '',
            '- [ ] It\'s submitted to the `dev` branch, _not_ the `main` branch',
            '',
            '**AI disclosure:** <!-- the model, the agent and the reasoning effort -->',
            '',
            '**Other information:**'
        ].join('\n');

        expect(disclosedFamiliesOf({body: template})).toEqual([]);
        expect(disclosedFamiliesOf({body: template.replace('<!-- the model, the agent and the reasoning effort -->', 'Claude Opus 5.5, Claude Code, high')})).toEqual(['claude'])
    });

    test('every family a pull request names counts, read across a CRLF body', () => {
        expect(disclosedFamiliesOf({body: 'Authored by Jo with Claude Code.\r\nCo-authored-by: Codex <codex@openai.com>\r\n'})).toEqual(['claude', 'gpt'])
    });

    test('nothing to read names nothing', () => {
        expect(disclosedFamiliesOf()).toEqual([]);
        expect(disclosedFamiliesOf({body: null, commitMessages: [null, undefined]})).toEqual([]);
        expect(disclosedFamiliesOf({body: 'Resolves #1\n\nA plain human description of the change.'})).toEqual([])
    })
});
